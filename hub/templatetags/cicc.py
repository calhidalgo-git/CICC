@register.simple_tag
def icon(name, css=''):
    """Icono SVG decorativo (aria-hidden). Usar junto a un texto o con aria-label en el contenedor."""
    body = ICONS.get(name, ICONS['file'])
    cls = f'icon {css}'.strip()
    return mark_safe(
        f'<svg class="{cls}" viewBox="0 0 24 24" width="1em" height="1em" fill="none" stroke="currentColor" '
        f'stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">{body}</svg>'
    )


@register.filter
def role_of(user):
    """Nombre del rol visible: primer grupo, o «Administrador» para superusuarios."""
    group = user.groups.first()
    if group:
        return group.name
    return 'Administrador' if user.is_superuser else 'Sin rol'


@register.filter
def highlight(text, query):
    """Escapa el texto y resalta (<mark>) las coincidencias con la búsqueda."""
    text = str(text)
    query = (query or '').strip()
    if not query:
        return text
    pattern = re.compile(re.escape(escape(query)), re.IGNORECASE)
    return mark_safe(pattern.sub(lambda m: f'<mark>{m.group(0)}</mark>', escape(text)))


@register.filter
def minutes_seconds(delta):
    """Formatea un timedelta como «12 min 05 s»."""
    if delta is None:
        return '—'
    total = int(delta.total_seconds())
    return f'{total // 60} min {total % 60:02d} s'


@register.filter
def get_item(mapping, key):
    return mapping.get(key)
